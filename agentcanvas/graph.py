"""Studio graph document storage and validation.

This module deliberately has no third-party dependencies: the document is a
portable artifact that can be generated by an agent or inspected by the local
server without a database.
"""

from __future__ import annotations

import copy
import json
import os
import uuid
from pathlib import Path, PureWindowsPath
from typing import Any, Callable, Dict, Mapping

from .canvas_v2 import CANVAS_V2_SCHEMA, detect_v1_canvas, migrate_canvas_v1_to_v2
from .core.app_surface import SUPPORTED_MANIFESTS, detect_app_surfaces
from .git_diff import get_git_status
from .ir import STATE_DIR_NAME, atomic_write_json, atomic_write_text, now_utc, resolve_workspace
from .workspace_lock import WORKSPACE_LOCK_FILENAME, WorkspaceLockBusy, workspace_write_lock

STUDIO_SCHEMA = "agentcanvas.studio.v3"
STUDIO_VERSION = 3
STUDIO_FILENAME = "studio.json"
ANNOTATIONS_FILENAME = "annotations.json"

_COMPONENT_KINDS = {"web", "mobile", "service", "package", "worker", "db", "external"}
_NODE_KINDS = {"When", "Do", "Decision", "Loop", "Parallel", "Join", "Wait", "SubFlow", "End"}
_NODE_STATUSES = {"verified", "inferred", "proposed", "stale"}
_DIFF_STATUSES = {"unchanged", "added", "modified", "removed"}
_EDGE_KINDS = {"normal", "branch", "loop_back", "parallel", "error", "async"}


def _nullable(schema: Dict[str, Any]) -> Dict[str, Any]:
    return {"anyOf": [schema, {"type": "null"}]}


def _object(properties: Dict[str, Any]) -> Dict[str, Any]:
    return {"type": "object", "additionalProperties": False, "required": list(properties), "properties": properties}


def studio_document_schema() -> Dict[str, Any]:
    """Return the strict JSON schema for a v3 studio document."""
    text = {"type": "string"}
    optional_text = _nullable(text)
    strings = {"type": "array", "items": text}
    line = {"type": "integer", "minimum": 1}
    diff_status = {"type": "string", "enum": sorted(_DIFF_STATUSES)}
    code_ref = _object({"path": text, "line": line, "end_line": line, "symbol": text})
    component = _object({
        "id": text, "name": text, "kind": {"type": "string", "enum": sorted(_COMPONENT_KINDS)},
        "path": text, "summary": text, "tech": strings, "entrypoints": strings, "diff_status": diff_status,
    })
    component_edge = _object({
        "id": text, "source": text, "target": text, "label": text, "protocol": text, "diff_status": diff_status,
    })
    node = _object({
        "id": text, "kind": {"type": "string", "enum": sorted(_NODE_KINDS)}, "title": text, "summary": text,
        "component_id": optional_text, "flow_ref": optional_text,
        "status": {"type": "string", "enum": sorted(_NODE_STATUSES)},
        "diff_status": diff_status, "diff_summary": optional_text,
        "code_refs": {"type": "array", "items": code_ref}, "test_ref": optional_text,
    })
    edge = _object({
        "id": text, "source": text, "target": text, "kind": {"type": "string", "enum": sorted(_EDGE_KINDS)},
        "label": text, "diff_status": diff_status,
    })
    flow = _object({
        "id": text, "title": text, "summary": text, "trigger": text, "component_ids": strings,
        "diff_status": diff_status, "diff_summary": optional_text,
        "nodes": {"type": "array", "items": node}, "edges": {"type": "array", "items": edge},
    })
    return _object({
        "schema": {"type": "string", "enum": [STUDIO_SCHEMA]},
        "version": {"type": "integer", "enum": [STUDIO_VERSION]},
        "revision": {"type": "integer", "minimum": 0}, "workspace": text, "workspace_name": text,
        "git_head": optional_text, "git_branch": optional_text,
        "mode": {"type": "string", "enum": ["map", "diff"]}, "diff_base": optional_text,
        "generated_at": text, "authored_by": text, "summary": text,
        "components": {"type": "array", "items": component},
        "component_edges": {"type": "array", "items": component_edge},
        "flows": {"type": "array", "items": flow},
    })


def studio_output_schema(kind: str = "map") -> Dict[str, Any]:
    """Strict response schema for agent-produced graph documents."""
    if kind in {"map", "diff"}:
        return studio_document_schema()
    if kind not in {"plan", "build"}:
        raise ValueError("kind must be map, diff, plan, or build")
    summary_field = "plan_summary" if kind == "plan" else "verification_summary"
    fields = {
        "status": {"type": "string", "enum": ["ready", "needs_input"]},
        "question": _nullable({"type": "string"}), summary_field: _nullable({"type": "string"}),
        "document": _nullable(studio_document_schema()),
    }
    if kind == "build":
        fields["verification"] = _nullable(_object({
            "command": _nullable({"type": "string"}),
            "passed": _nullable({"type": "boolean"}),
            "output": _nullable({"type": "string"}),
        }))
    return _object(fields)


def _require_object(value: Any, label: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise ValueError(f"{label} must be an object")
    return value


def _keys(value: Mapping[str, Any], allowed: set[str], label: str) -> None:
    missing, extra = allowed - set(value), set(value) - allowed
    if missing or extra:
        raise ValueError(f"{label} has invalid fields (missing={sorted(missing)}, extra={sorted(extra)})")


def _string(value: Any, label: str, *, nullable: bool = False) -> None:
    if value is None and nullable:
        return
    if not isinstance(value, str):
        raise ValueError(f"{label} must be {'a string or null' if nullable else 'a string'}")


def _repo_path(value: Any, label: str, *, nullable: bool = False) -> None:
    _string(value, label, nullable=nullable)
    if value is None:
        return
    candidate = Path(value)
    windows = PureWindowsPath(value)
    if not value or "\x00" in value or candidate.is_absolute() or windows.drive or windows.root or ".." in windows.parts:
        raise ValueError(f"{label} must be a workspace-relative path")


def _enum(value: Any, choices: set[str], label: str) -> None:
    if not isinstance(value, str) or value not in choices:
        raise ValueError(f"{label} has an invalid value")


def _id_set(values: list[Any], label: str) -> set[str]:
    result: set[str] = set()
    for value in values:
        _string(value, label)
        if not value or value in result:
            raise ValueError(f"{label} values must be non-empty and unique")
        result.add(value)
    return result


def validate_studio_document(doc: Any) -> Dict[str, Any]:
    """Validate a v3 document and return a detached copy on success."""
    doc = _require_object(doc, "document")
    root_keys = {"schema", "version", "revision", "workspace", "workspace_name", "git_head", "git_branch", "mode", "diff_base", "generated_at", "authored_by", "summary", "components", "component_edges", "flows"}
    _keys(doc, root_keys, "document")
    if doc["schema"] != STUDIO_SCHEMA or type(doc["version"]) is not int or doc["version"] != STUDIO_VERSION:
        raise ValueError("document must be agentcanvas.studio.v3 version 3")
    if type(doc["revision"]) is not int or doc["revision"] < 0:
        raise ValueError("document.revision must be a non-negative integer")
    workspace = doc["workspace"]
    _string(workspace, "document.workspace")
    if not os.path.isabs(workspace):
        raise ValueError("document.workspace must be absolute")
    for key in ("workspace_name", "generated_at", "authored_by", "summary"):
        _string(doc[key], f"document.{key}")
    for key in ("git_head", "git_branch", "diff_base"):
        _string(doc[key], f"document.{key}", nullable=True)
    _enum(doc["mode"], {"map", "diff"}, "document.mode")
    for key in ("components", "component_edges", "flows"):
        if not isinstance(doc[key], list):
            raise ValueError(f"document.{key} must be an array")

    component_ids = _id_set([item.get("id") if isinstance(item, Mapping) else None for item in doc["components"]], "component id")
    for index, raw in enumerate(doc["components"]):
        item = _require_object(raw, f"component[{index}]")
        keys = {"id", "name", "kind", "path", "summary", "tech", "entrypoints", "diff_status"}
        _keys(item, keys, f"component[{index}]")
        for key in ("id", "name", "summary"):
            _string(item[key], f"component[{index}].{key}")
        _repo_path(item["path"], f"component[{index}].path")
        _enum(item["kind"], _COMPONENT_KINDS, f"component[{index}].kind")
        _enum(item["diff_status"], _DIFF_STATUSES, f"component[{index}].diff_status")
        if not isinstance(item["tech"], list) or not isinstance(item["entrypoints"], list):
            raise ValueError(f"component[{index}] tech and entrypoints must be arrays")
        for value in item["tech"]:
            _string(value, f"component[{index}] tech value")
        for value in item["entrypoints"]:
            _repo_path(value, f"component[{index}] entrypoint")

    _id_set([item.get("id") if isinstance(item, Mapping) else None for item in doc["component_edges"]], "component edge id")
    for index, raw in enumerate(doc["component_edges"]):
        item = _require_object(raw, f"component_edge[{index}]")
        _keys(item, {"id", "source", "target", "label", "protocol", "diff_status"}, f"component_edge[{index}]")
        for key in ("id", "source", "target", "label", "protocol"):
            _string(item[key], f"component_edge[{index}].{key}")
        if item["source"] not in component_ids or item["target"] not in component_ids:
            raise ValueError(f"component_edge[{index}] references an unknown component")
        _enum(item["diff_status"], _DIFF_STATUSES, f"component_edge[{index}].diff_status")

    flow_ids = _id_set([item.get("id") if isinstance(item, Mapping) else None for item in doc["flows"]], "flow id")
    for index, raw in enumerate(doc["flows"]):
        _validate_flow(_require_object(raw, f"flow[{index}]"), index, component_ids, flow_ids)
    return copy.deepcopy(dict(doc))


def _validate_flow(flow: Mapping[str, Any], index: int, component_ids: set[str], flow_ids: set[str]) -> None:
    keys = {"id", "title", "summary", "trigger", "component_ids", "diff_status", "diff_summary", "nodes", "edges"}
    _keys(flow, keys, f"flow[{index}]")
    for key in ("id", "title", "summary", "trigger"):
        _string(flow[key], f"flow[{index}].{key}")
    _string(flow["diff_summary"], f"flow[{index}].diff_summary", nullable=True)
    _enum(flow["diff_status"], _DIFF_STATUSES, "flow.diff_status")
    for key in ("component_ids", "nodes", "edges"):
        if not isinstance(flow[key], list):
            raise ValueError(f"flow[{index}].{key} must be an array")
    for component_id in flow["component_ids"]:
        _string(component_id, "flow.component_id")
        if component_id not in component_ids:
            raise ValueError(f"flow[{index}] references an unknown component")
    node_ids = _id_set([item.get("id") if isinstance(item, Mapping) else None for item in flow["nodes"]], "node id")
    for node_index, raw in enumerate(flow["nodes"]):
        node = _require_object(raw, f"flow[{index}].node[{node_index}]")
        keys = {"id", "kind", "title", "summary", "component_id", "flow_ref", "status", "diff_status", "diff_summary", "code_refs", "test_ref"}
        _keys(node, keys, f"flow[{index}].node[{node_index}]")
        for key in ("id", "title", "summary"):
            _string(node[key], f"node.{key}")
        for key in ("component_id", "flow_ref", "diff_summary"):
            _string(node[key], f"node.{key}", nullable=True)
        _repo_path(node["test_ref"], "node.test_ref", nullable=True)
        _enum(node["kind"], _NODE_KINDS, "node.kind")
        _enum(node["status"], _NODE_STATUSES, "node.status")
        _enum(node["diff_status"], _DIFF_STATUSES, "node.diff_status")
        if node["component_id"] is not None and node["component_id"] not in component_ids:
            raise ValueError("node references an unknown component")
        if node["flow_ref"] is not None and node["flow_ref"] not in flow_ids:
            raise ValueError("node references an unknown flow")
        if not isinstance(node["code_refs"], list):
            raise ValueError("node.code_refs must be an array")
        for ref in node["code_refs"]:
            ref = _require_object(ref, "code_ref")
            _keys(ref, {"path", "line", "end_line", "symbol"}, "code_ref")
            _repo_path(ref["path"], "code_ref.path")
            _string(ref["symbol"], "code_ref.symbol")
            if type(ref["line"]) is not int or type(ref["end_line"]) is not int or ref["line"] < 1 or ref["end_line"] < ref["line"]:
                raise ValueError("code_ref lines must be positive and ordered")
    _id_set([item.get("id") if isinstance(item, Mapping) else None for item in flow["edges"]], "flow edge id")
    for edge in flow["edges"]:
        edge = _require_object(edge, "flow edge")
        _keys(edge, {"id", "source", "target", "kind", "label", "diff_status"}, "flow edge")
        for key in ("id", "source", "target", "label"):
            _string(edge[key], f"flow edge.{key}")
        if edge["source"] not in node_ids or edge["target"] not in node_ids:
            raise ValueError("flow edge references an unknown node")
        _enum(edge["kind"], _EDGE_KINDS, "flow edge.kind")
        _enum(edge["diff_status"], _DIFF_STATUSES, "flow edge.diff_status")


def _state_file(root: Path, name: str) -> Path:
    state = root / STATE_DIR_NAME
    if state.is_symlink():
        raise ValueError(".agentcanvas must not be a symlink")
    path = state / name
    if path.is_symlink():
        raise ValueError(f"{name} must not be a symlink")
    return path


class StudioRevisionConflict(RuntimeError):
    def __init__(self) -> None:
        super().__init__("REVISION_CONFLICT")


def _read_studio_revision(path: Path) -> int | None:
    try:
        previous = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return 0
    except (OSError, ValueError, RecursionError):
        return None
    revision = previous.get("revision") if isinstance(previous, Mapping) else None
    return revision if type(revision) is int and revision >= 0 else None


def studio_revision(root: str | Path) -> int:
    revision = _read_studio_revision(_state_file(resolve_workspace(root), STUDIO_FILENAME))
    if revision is None:
        raise StudioRevisionConflict()
    return revision


def save_studio_document(
    root: str | Path, doc: Any, *, expected_revision: int | None = None,
) -> Dict[str, Any]:
    root = resolve_workspace(root)
    candidate = validate_studio_document(doc)
    if Path(candidate["workspace"]).resolve() != root:
        raise ValueError("document.workspace must match the target workspace")
    _state_file(root, STUDIO_FILENAME)
    _state_file(root, WORKSPACE_LOCK_FILENAME)
    try:
        with workspace_write_lock(root, writer="save-studio-document"):
            path = _state_file(root, STUDIO_FILENAME)
            revision = _read_studio_revision(path)
            if expected_revision is not None and revision != expected_revision:
                raise StudioRevisionConflict()
            candidate["revision"] = (revision or 0) + 1
            atomic_write_json(path, candidate)
    except WorkspaceLockBusy as exc:
        raise ValueError(str(exc)) from exc
    return candidate


def load_studio_document(root: str | Path) -> tuple[Dict[str, Any], bool]:
    root = resolve_workspace(root)
    path = _state_file(root, STUDIO_FILENAME)
    if path.exists():
        try:
            document = validate_studio_document(json.loads(path.read_text(encoding="utf-8")))
            return document, bool(document["flows"])
        except (OSError, ValueError):
            pass
    legacy = _state_file(root, "canvas.ir.json")
    if legacy.exists():
        try:
            raw = _require_object(json.loads(legacy.read_text(encoding="utf-8")), "legacy canvas")
            document = _adapt_legacy(root, raw)
            return document, bool(document["flows"])
        except (OSError, ValueError):
            pass
    document = _synthesize_document(root)
    return document, False


def _empty_document(root: Path, *, summary: str) -> Dict[str, Any]:
    git = get_git_status(root)
    return {
        "schema": STUDIO_SCHEMA, "version": STUDIO_VERSION, "revision": 0,
        "workspace": str(root), "workspace_name": root.name, "git_head": git["head"],
        "git_branch": git["branch"], "mode": "map", "diff_base": None,
        "generated_at": now_utc(), "authored_by": "agentcanvas", "summary": summary,
        "components": [], "component_edges": [], "flows": [],
    }


def _synthesize_document(root: Path) -> Dict[str, Any]:
    document = _empty_document(root, summary="Discovered workspace components.")
    ignored = {STATE_DIR_NAME, ".git", "node_modules", ".venv", "venv", "dist", "build", "__pycache__"}
    files = []
    for visited, (directory, names, filenames) in enumerate(os.walk(root)):
        if visited == 256 or len(files) >= 4_000:
            break
        folder = Path(directory)
        depth = len(folder.relative_to(root).parts)
        names[:] = sorted(name for name in names if depth < 4 and name not in ignored and not name.startswith("."))
        ordered = sorted(filenames, key=lambda name: (name not in SUPPORTED_MANIFESTS, name))
        for name in ordered[:4_000 - len(files)]:
            path = folder / name
            if not path.is_symlink() and path.is_file():
                files.append(path)
    try:
        surfaces = detect_app_surfaces(root, files)
    except (OSError, ValueError):
        surfaces = []
    for surface in surfaces:
        surface_type = str(surface.get("type", "package"))
        kind = {"backend": "service", "cli": "worker"}.get(surface_type, surface_type)
        if kind not in _COMPONENT_KINDS: kind = "package"
        document["components"].append({"id": str(surface["id"]), "name": str(surface.get("name") or surface["id"]), "kind": kind, "path": str(surface.get("root") or "."), "summary": f"Discovered {kind} component.", "tech": sorted(str(value) for value in surface.get("frameworks", [])), "entrypoints": [str(item.get("path")) for item in surface.get("entry_hints", []) if isinstance(item, Mapping) and item.get("path")], "diff_status": "unchanged"})
    if not document["components"]:
        document["components"].append({"id": "workspace", "name": root.name, "kind": "package", "path": ".", "summary": "Workspace root.", "tech": [], "entrypoints": [], "diff_status": "unchanged"})
    return validate_studio_document(document)


def _adapt_legacy(root: Path, legacy: Mapping[str, Any]) -> Dict[str, Any]:
    native = legacy.get("canvas_v2")
    if isinstance(native, Mapping) and native.get("schema") == CANVAS_V2_SCHEMA:
        legacy = native
    elif detect_v1_canvas(legacy):
        legacy = migrate_canvas_v1_to_v2(legacy, authored_by="agentcanvas")
    app = legacy.get("app") if isinstance(legacy.get("app"), Mapping) else {}
    document = _empty_document(root, summary=str(legacy.get("summary") or app.get("summary") or "Adapted legacy canvas."))
    if isinstance(legacy.get("authored_by"), str):
        document["authored_by"] = legacy["authored_by"]
    if isinstance(legacy.get("updated_at"), str):
        document["generated_at"] = legacy["updated_at"]
    facts = _legacy_facts(root)
    component_id = "workspace"
    document["components"] = [{"id": component_id, "name": root.name, "kind": "package", "path": ".", "summary": "Workspace component from legacy canvas.", "tech": [], "entrypoints": [], "diff_status": "unchanged"}]
    journeys = legacy.get("journeys") or legacy.get("flows") or []
    if not isinstance(journeys, list):
        raise ValueError("legacy flows must be an array")
    for number, journey in enumerate(journeys):
        if not isinstance(journey, Mapping):
            continue
        flow_id = str(journey.get("id") or f"legacy-flow-{number + 1}")
        raw_nodes = journey.get("nodes") or journey.get("steps") or []
        if not isinstance(raw_nodes, list):
            raise ValueError("legacy nodes must be an array")
        nodes, edges, previous = [], [], None
        for node_number, raw in enumerate(raw_nodes):
            if not isinstance(raw, Mapping):
                continue
            node_id = str(raw.get("id") or f"{flow_id}-node-{node_number + 1}")
            raw_kind = str(raw.get("kind") or raw.get("role") or "Do")
            kind = {"If": "Decision", "ElseIf": "Decision", "Else": "Decision"}.get(raw_kind, raw_kind)
            if kind not in _NODE_KINDS:
                kind = "Do"
            title = str(raw.get("title") or raw.get("text") or raw.get("condition") or kind)
            refs = raw.get("code_refs") or raw.get("evidence_refs") or raw.get("refs") or []
            code_refs = []
            if isinstance(refs, list):
                for ref in refs:
                    code_ref = _legacy_code_ref(facts.get(ref) if isinstance(ref, str) else ref)
                    if code_ref and code_ref not in code_refs:
                        code_refs.append(code_ref)
            status = raw.get("status")
            nodes.append({
                "id": node_id, "kind": kind, "title": title,
                "summary": str(raw.get("summary") or raw.get("detail") or ""),
                "component_id": component_id, "flow_ref": raw.get("flow_ref"),
                "status": status if isinstance(status, str) and status in _NODE_STATUSES else "inferred",
                "diff_status": "unchanged", "diff_summary": None, "code_refs": code_refs,
                "test_ref": raw.get("test_ref") if isinstance(raw.get("test_ref"), str) else None,
            })
            if previous and not isinstance(journey.get("edges"), list):
                edges.append({"id": f"{flow_id}-edge-{node_number}", "source": previous, "target": node_id, "kind": "normal", "label": "", "diff_status": "unchanged"})
            previous = node_id
        if isinstance(journey.get("edges"), list):
            for raw_edge in journey["edges"]:
                if not isinstance(raw_edge, Mapping):
                    continue
                old_kind = str(raw_edge.get("kind") or "normal")
                edge_kind = {"loop_body": "normal", "loop_exit": "branch"}.get(old_kind, old_kind)
                if edge_kind not in _EDGE_KINDS:
                    edge_kind = "normal"
                edges.append({"id": str(raw_edge.get("id") or f"{flow_id}-edge-{len(edges)+1}"), "source": str(raw_edge.get("source") or ""), "target": str(raw_edge.get("target") or ""), "kind": edge_kind, "label": str(raw_edge.get("label") or ""), "diff_status": "unchanged"})
        entry_title = next((node["title"] for node in nodes if node["id"] == journey.get("entry_node")), None)
        document["flows"].append({
            "id": flow_id, "title": str(journey.get("title") or flow_id),
            "summary": str(journey.get("summary") or ""),
            "trigger": str(journey.get("trigger") or journey.get("entry") or entry_title or "Legacy flow"),
            "component_ids": [component_id], "diff_status": "unchanged", "diff_summary": None,
            "nodes": nodes, "edges": edges,
        })
    return validate_studio_document(document)


def _legacy_facts(root: Path) -> dict[str, Mapping[str, Any]]:
    try:
        path = _state_file(root, "workflow.ir.json")
        workflow = _require_object(json.loads(path.read_text(encoding="utf-8")), "legacy workflow")
    except (OSError, ValueError):
        return {}
    source = workflow.get("source_facts")
    sources = (workflow.get("nodes"), source.get("facts") if isinstance(source, Mapping) else None)
    return {
        fact["id"]: fact
        for records in sources if isinstance(records, list)
        for fact in records if isinstance(fact, Mapping) and isinstance(fact.get("id"), str)
    }


def _legacy_code_ref(fact: Any) -> dict | None:
    if not isinstance(fact, Mapping):
        return None
    provenance = fact.get("provenance")
    if isinstance(provenance, list):
        provenance = next((record for record in provenance if isinstance(record, Mapping)), None)
    location = provenance.get("location", provenance) if isinstance(provenance, Mapping) else fact
    if not isinstance(location, Mapping):
        return None
    path = location.get("path") or fact.get("file")
    line = location.get("line")
    end = location.get("end_line", line)
    if type(line) is not int or type(end) is not int or line < 1 or end < line:
        return None
    try:
        _repo_path(path, "legacy code ref path")
    except ValueError:
        return None
    symbol = fact.get("symbol") or fact.get("name") or fact.get("subject")
    return {"path": path, "line": line, "end_line": end, "symbol": symbol if isinstance(symbol, str) else ""}


class AnnotationsStore:
    """Small, workspace-confined store for graph annotations."""
    _fields = {"id", "target_type", "target_id", "flow_id", "text", "author", "created_at", "resolved"}

    def __init__(
        self, root: str | Path, *, on_update: Callable[[list[Dict[str, Any]]], None] | None = None,
    ) -> None:
        self.root = resolve_workspace(root)
        self.on_update = on_update

    def load(self) -> list[Dict[str, Any]]:
        path = _state_file(self.root, ANNOTATIONS_FILENAME)
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            return []
        except (OSError, ValueError) as exc:
            raise ValueError("annotations.json must be valid JSON") from exc
        if not isinstance(payload, list):
            raise ValueError("annotations.json must be an array")
        records = [self._validate(item) for item in payload]
        _id_set([record["id"] for record in records], "annotation id")
        return records

    def create(self, **payload: Any) -> Dict[str, Any]:
        if set(payload) - (self._fields - {"id", "created_at"}):
            raise ValueError("unsupported annotation field")
        payload.update(id=uuid.uuid4().hex, created_at=now_utc())
        payload.setdefault("resolved", False)
        payload.setdefault("author", "unknown")
        payload.setdefault("flow_id", None)
        record = self._validate(payload)
        return self._mutate(lambda records: records + [record])[-1]

    def update(self, annotation_id: str, **payload: Any) -> Dict[str, Any]:
        if set(payload) - (self._fields - {"id", "created_at"}):
            raise ValueError("unsupported annotation field")

        def mutate(records: list[Dict[str, Any]]) -> list[Dict[str, Any]]:
            for index, record in enumerate(records):
                if record["id"] == annotation_id:
                    replacement = self._validate({**record, **payload})
                    return records[:index] + [replacement] + records[index + 1:]
            raise LookupError(annotation_id)

        return next(record for record in self._mutate(mutate) if record["id"] == annotation_id)

    def delete(self, annotation_id: str) -> None:
        def mutate(records: list[Dict[str, Any]]) -> list[Dict[str, Any]]:
            result = [record for record in records if record["id"] != annotation_id]
            if len(result) == len(records):
                raise LookupError(annotation_id)
            return result

        self._mutate(mutate)

    def _mutate(self, mutation: Any) -> list[Dict[str, Any]]:
        _state_file(self.root, ANNOTATIONS_FILENAME)
        _state_file(self.root, WORKSPACE_LOCK_FILENAME)
        try:
            with workspace_write_lock(self.root, writer="studio-annotations"):
                path = _state_file(self.root, ANNOTATIONS_FILENAME)
                records = self.load()
                updated = mutation(records)
                atomic_write_text(path, json.dumps(updated, indent=2, sort_keys=True) + "\n")
                if self.on_update is not None:
                    self.on_update(updated)
                return updated
        except WorkspaceLockBusy as exc:
            raise ValueError(str(exc)) from exc

    def _validate(self, value: Any) -> Dict[str, Any]:
        value = _require_object(value, "annotation")
        _keys(value, self._fields, "annotation")
        for key in ("id", "target_type", "target_id", "text", "author", "created_at"):
            _string(value[key], f"annotation.{key}")
            if not value[key].strip():
                raise ValueError(f"annotation.{key} must not be empty")
        _string(value["flow_id"], "annotation.flow_id", nullable=True)
        if type(value["resolved"]) is not bool:
            raise ValueError("annotation.resolved must be boolean")
        return copy.deepcopy(dict(value))


